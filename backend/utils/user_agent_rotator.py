class UserAgentRotator:
    """Provides random user agents for browser requests."""

    @staticmethod
    def get_random() -> str:
        """Return a random user agent from the full pool."""
        return random.choice(USER_AGENTS)

    @staticmethod
    def get_desktop() -> str:
        """Return a random desktop user agent."""
        desktop_uas = [ua for ua in USER_AGENTS if "Mobile" not in ua and "iPhone" not in ua]
        return random.choice(desktop_uas)

    @staticmethod
    def get_mobile() -> str:
        """Return a random mobile user agent."""
        mobile_uas = [ua for ua in USER_AGENTS if "Mobile" in ua or "iPhone" in ua]
        return random.choice(mobile_uas)

    @staticmethod
    def get_indian_mobile() -> str:
        """Return an Indian mobile device user agent (for JustDial/IndiaMart)."""
        return random.choice(INDIAN_MOBILE_USER_AGENTS)

    @staticmethod
    def get_headers(ua: str | None = None) -> dict[str, str]:
        """Return a full set of realistic HTTP headers."""
        user_agent = ua or UserAgentRotator.get_desktop()
        return {
            "User-Agent": user_agent,
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8",
            "Accept-Language": "en-IN,en-US;q=0.9,en;q=0.8",
            "Accept-Encoding": "gzip, deflate, br",
            "Connection": "keep-alive",
            "Upgrade-Insecure-Requests": "1",
            "Sec-Fetch-Dest": "document",
            "Sec-Fetch-Mode": "navigate",
            "Sec-Fetch-Site": "none",
            "Sec-Fetch-User": "?1",
            "Cache-Control": "max-age=0",
        }
