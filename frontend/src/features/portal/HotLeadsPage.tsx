import React from 'react'
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query'
import { fetchLeads, Lead } from '@/features/leads/api'
import { crmApi } from '@/features/crm/api'
import { PipelineStage } from '@/features/crm/types'
import { LeadCard } from '@/components/ui/LeadCard'
import { motion } from 'framer-motion'
import { ArrowRight, Loader2 } from 'lucide-react'
import { Button } from '@/components/ui/button'

export function HotLeadsPage() {
  const queryClient = useQueryClient()

  const { data: leads = [], isLoading } = useQuery({
    queryKey: ['leads'],
    queryFn: () => fetchLeads(true),
  })

  // Filter for final available hot leads
  const hotLeads = leads.filter(l => l.status === 'NEW' || l.status === 'QUALIFIED')

  const claimMutation = useMutation({
    mutationFn: async (lead: Lead) => {
      // 1. Create a CRM Opportunity for this lead
      await crmApi.createOpportunity({
        lead_id: lead.id,
        title: lead.business_name,
        pipeline_stage: PipelineStage.NEW,
        value: 1000,
        probability: lead.score || 50,
      })
      
      // Note: Ideally, we'd also update the lead status to 'CONTACTED' or 'CLAIMED' 
      // by calling a backend update endpoint here if it exists.
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['leads'] })
      queryClient.invalidateQueries({ queryKey: ['opportunities'] })
    }
  })

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      className="space-y-6"
    >
      <div>
        <h1 className="text-3xl font-bold text-gray-900 tracking-tight">Hot Leads Market</h1>
        <p className="text-gray-500 mt-2">Browse the latest refined leads generated by our automation engine.</p>
      </div>
      
      {isLoading ? (
        <div className="glass-panel rounded-3xl p-12 text-center border border-white/40 flex flex-col items-center justify-center">
          <Loader2 className="w-8 h-8 animate-spin text-pink-400 mb-4" />
          <p className="text-gray-500">Loading your hot leads...</p>
        </div>
      ) : hotLeads.length === 0 ? (
        <div className="glass-panel rounded-3xl p-12 text-center border border-white/40">
          <p className="text-gray-500">No hot leads available in the market right now.</p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-6">
          {hotLeads.map((lead, i) => (
            <motion.div
              key={lead.id}
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: i * 0.05 }}
            >
              <LeadCard 
                lead={lead} 
                actionButton={
                  <Button
                    onClick={() => claimMutation.mutate(lead)}
                    disabled={claimMutation.isPending}
                    variant="outline"
                    className="bg-white/50 border-blue-200 text-blue-600 hover:bg-white hover:text-blue-700 shadow-sm transition-all text-xs h-8 px-3"
                  >
                    Claim <ArrowRight className="w-3.5 h-3.5 ml-1.5" />
                  </Button>
                }
              />
            </motion.div>
          ))}
        </div>
      )}
    </motion.div>
  )
}
